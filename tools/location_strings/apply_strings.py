#!/usr/bin/env python3
"""Writes the Custom Location strings (strings_data.py) into every res/values*/strings.xml.
Idempotent: strips a previous generated block first. bqi-rIR reuses the Persian text.
Usage: python3 apply_strings.py <path to app/src/main/res>"""
import re, sys
from strings_data import S, LOCALES

res = sys.argv[1]
BEGIN, END = "    <!-- BEGIN custom-location (generated by tools/location_strings) -->", "    <!-- END custom-location -->"

def esc(t):
    return t.replace("&", "&amp;").replace("<", "&lt;").replace("'", "\\'").replace('"', '\\"')

def block(idx, extra=""):
    lines = [BEGIN]
    for row in S:
        lines.append(f'    <string name="{row[0]}">{esc(row[1 + idx])}</string>')
    lines.append(extra + END)
    return "\n".join(lines) + "\n"

NONTRANSLATABLE = ('    <string name="cl_ip_v4" translatable="false">IPv4</string>\n'
                   '    <string name="cl_ip_v6" translatable="false">IPv6</string>\n')

targets = [(l, i) for i, l in enumerate(LOCALES)] + [("values-bqi-rIR", LOCALES.index("values-fa"))]
for folder, idx in targets:
    path = f"{res}/{folder}/strings.xml"
    text = open(path, encoding="utf-8").read()
    text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", "", text, flags=re.S)
    extra = NONTRANSLATABLE if folder == "values" else ""
    new = block(idx, extra)
    assert "</resources>" in text, path
    text = text.replace("</resources>", new + "\n</resources>", 1) if not text.rstrip().endswith("</resources>") else \
        text.rstrip()[: -len("</resources>")].rstrip("\n") + "\n\n" + new + "\n</resources>\n"
    open(path, "w", encoding="utf-8").write(text)
    print("updated", folder, len(S))
